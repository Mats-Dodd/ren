#!/usr/bin/env bash
# core/build.sh: build the Phase C C core (copied from experiments/native-lang/c,
# with the E1 additions) as static libraries + headers, and the test binaries.
# Machine: cloud (experiments/MACHINE-cloud.md). Runs under the SHARED lock.
#
#   ./build.sh [profile ...]        default: release check asan tsan
#
# profiles (all clang 18):
#   release  -O2 -g -DNDEBUG            the measured core: no debug checks
#   check    -O2 -g                     the same code with REN_C_DEBUG on (drain-contract
#                                        and leaf-callback asserts, one-pending-call assert)
#   debug    -O0 -g                     REN_C_DEBUG on
#   asan     -O1 -g ASan+UBSan          REN_C_DEBUG on, -fno-sanitize-recover=undefined
#   tsan     -O1 -g TSan                REN_C_DEBUG on
#
# outputs, per profile P (git-ignored):
#   build/P/include/   slice.h ren_e1.h                 (the public headers)
#   build/P/lib/       libren_core.a                    core + drivers (epoll, uring, replay, fuzz)
#                      libren_rt.a                      rt.c + hot.c (ren_obj_free, ren_task_new, ren_rc_*, ren_hot_*)
#                      libren_wl.a                      the Phase B workloads (w1 w2 w3 t_* w_fuzz) + registry
#   build/P/env.sh     REN_CC REN_CFLAGS REN_INC REN_LIBS (source it; see core/README.md)
#   bin/P/             harness abi_test deque_stress layout_check fuzz_run jdump  (Phase B tests)
#                      e1_drain e1_digest e1_race e1_two          (E1 tests)
#
# env: PLANT=B5 builds the core with the Phase B deliver order (the §B.5 window
#      re-opened) into build/P-B5, bin/P-B5, for the regression test only.
#      E1_DELAY=1 (implied by tests needing it) compiles the test-only delay hook.
set -euo pipefail

if [ -z "${REN_FLOCKED:-}" ]; then
  mkdir -p /tmp/ren-bench
  export REN_FLOCKED=1
  exec flock -s /tmp/ren-bench/lock "$0" "$@"
fi

ROOT=$(cd "$(dirname "$0")" && pwd)
S=$ROOT/src; H=$ROOT/harness; I=$ROOT/include; T=$ROOT/tests
CC=${CC:-clang}
PROFILES=("$@"); [ ${#PROFILES[@]} -gt 0 ] || PROFILES=(release check asan tsan)

CORE_SRC=(dq.c journal.c sched.c core.c layout.c drv_common.c drv_epoll.c drv_replay.c drv_uring.c)
WL_SRC=(workloads/wl_common.c workloads/w1_spawn.c workloads/w2_switch.c workloads/w3_rtt.c
        workloads/t_io.c workloads/w_fuzz.c workloads/t_race.c)
WARN="-std=gnu11 -Wall -Wextra -Wno-unused-parameter -Werror"

flags() {
  case "$1" in
    release) echo "-O2 -g -DNDEBUG" ;;
    check)   echo "-O2 -g" ;;
    debug)   echo "-O0 -g" ;;
    asan)    echo "-O1 -g -fno-omit-frame-pointer -fsanitize=address,undefined -fno-sanitize-recover=undefined" ;;
    tsan)    echo "-O1 -g -fsanitize=thread" ;;
    *) echo "build.sh: unknown profile $1" >&2; exit 1 ;;
  esac
}

build_one() {
  local prof=$1 tag=$1 extra=""
  if [ "${PLANT:-}" = B5 ]; then tag="$prof-B5"; extra="-DREN_PLANT_B5=1"; fi
  local fl; fl="$(flags "$prof") -D_GNU_SOURCE -DREN_E1_HOOKS=1 $extra"
  local out=$ROOT/build/$tag bin=$ROOT/bin/$tag
  rm -rf "$out"; mkdir -p "$out/obj" "$out/lib" "$out/include" "$bin"
  local t0; t0=$(date +%s.%N)
  local objs=()
  for f in "${CORE_SRC[@]}"; do
    $CC $fl $WARN -I"$I" -I"$S" -c "$S/$f" -o "$out/obj/${f%.c}.o"
    objs+=("$out/obj/${f%.c}.o")
  done
  ar rcs "$out/lib/libren_core.a" "${objs[@]}"
  $CC $fl $WARN -I"$I" -c "$H/rt.c" -o "$out/obj/rt.o"
  $CC $fl $WARN -I"$I" -I"$S" -c "$S/hot.c" -o "$out/obj/hot.o"
  ar rcs "$out/lib/libren_rt.a" "$out/obj/rt.o" "$out/obj/hot.o"
  local wobjs=()
  for f in "${WL_SRC[@]}"; do
    local o="$out/obj/wl_$(basename "${f%.c}").o"
    $CC $fl $WARN -I"$I" -I"$H" -c "$H/$f" -o "$o"
    wobjs+=("$o")
  done
  ar rcs "$out/lib/libren_wl.a" "${wobjs[@]}"
  cp "$I"/*.h "$out/include/"
  local san; san=$(flags "$prof" | grep -o -- '-fsanitize=[^ ]*' || true)
  cat > "$out/env.sh" <<EOF
# source me: the C core, profile $tag (machine cloud). Generated by core/build.sh.
REN_CORE_PROFILE=$tag
REN_CC=$CC
REN_INC="-I$out/include"
REN_CFLAGS="$(flags "$prof") -D_GNU_SOURCE -I$out/include"
REN_LIBS="$out/lib/libren_core.a $out/lib/libren_rt.a -luring -lpthread -lm${san:+ $san}"
REN_WL_LIB="$out/lib/libren_wl.a"
REN_HARNESS_INC="-I$H"
EOF
  local libs="$out/lib/libren_wl.a $out/lib/libren_core.a $out/lib/libren_rt.a -luring -lpthread -lm"
  local hf="$fl $WARN -I$I -I$H"
  $CC $hf "$H/host_main.c" $libs -o "$bin/harness"
  $CC $hf "$H/tests/abi_test.c" $libs -o "$bin/abi_test"
  $CC $hf "$H/tests/deque_stress.c" $libs -o "$bin/deque_stress"
  $CC $hf "$H/tests/layout_check.c" $libs -o "$bin/layout_check"
  $CC $hf "$H/fuzz/fuzz_run.c" "$H/fuzz/fuzz_common.c" $libs -o "$bin/fuzz_run"
  $CC $hf "$H/tests/jdump.c" -o "$bin/jdump"
  for t in e1_drain e1_digest e1_race e1_two; do
    $CC $hf -I"$S" "$T/$t.c" $libs -o "$bin/$t"
  done
  if [ "$prof" = asan ]; then
    $CC -O1 -g -fsanitize=fuzzer,address,undefined -D_GNU_SOURCE -I"$I" -I"$H" "$H/fuzz/fuzz_target.c" \
      "$H/fuzz/fuzz_common.c" $libs -o "$bin/fuzz" 2>/dev/null || echo "note: libFuzzer target did not link"
  fi
  local t1; t1=$(date +%s.%N)
  printf 'built %s in %.1fs -> %s\n' "$tag" "$(echo "$t1 - $t0" | bc)" "$out"
}

for p in "${PROFILES[@]}"; do build_one "$p"; done

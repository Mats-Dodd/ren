"""Writes one program, in Ren or in Go, of about the lines asked for: H6,
how compile time grows with a program's size.

    python3 -I gen.py ren 10000 OUT      # OUT/main.ren and OUT/m0000.ren ...
    python3 -I gen.py go 10000 OUT       # OUT/go.mod, OUT/main.go, OUT/m0000/ ...

Both languages get the same shape: many small modules, each with a
record type, a sum type, and a few units of functions over them
(construct, match, change through `&` or a pointer, loop). Module k
imports modules 2k + 1 and 2k + 2, so they form a balanced tree under
main, and a compiler can build siblings in parallel. Everything is in
the first-order subset native steps 2 and 3 compile: records, sum types,
`match`, `for`, `&`, and `print`. Running it prints one checksum.

Each language gets the lines asked for, so Go, which spends more lines
on a sum type and a loop, gets fewer modules: the two are the same
shape and size, not the same program.
"""

import os
import sys

UNITS = 4  # units of functions in each module


def ren_module(k, count):
    children = [c for c in (2 * k + 1, 2 * k + 2) if c < count]
    out = ["// generated by bench/native/gen/gen.py: module %d of %d" % (k, count)]
    out += ["import m%04d" % c for c in children]
    out += [
        "",
        "pub type Item = { id: Int, weight: Int, kind: Kind }",
        "",
        "pub type Kind =",
        "  | Small",
        "  | Large(size: Int)",
        "  | Pair(a: Int, b: Int)",
    ]
    for j in range(UNITS):
        s = k + j  # what makes this unit's numbers its own
        out += [
            "",
            "fn kind_%d(i: Int) -> Kind =" % j,
            "  if i % 3 == 0 then Small",
            "  else if i %% 3 == 1 then Large(i + %d)" % s,
            "  else Pair(i, %d)" % s,
            "",
            "fn weigh_%d(k: Kind) -> Int =" % j,
            "  match k",
            "    Small => %d" % (s % 10),
            "    Large(size) => size * 2 + %d" % (s % 7),
            "    Pair(a, b) => a + b %% %d" % (s % 5 + 1),
            "",
            "fn grow_%d(inout it: Item, by: Int) =" % j,
            "  it.weight += by + %d" % (s % 3),
            "  it.id += 1",
            "",
            "fn score_%d(n: Int) -> Int =" % j,
            "  var total = 0",
            "  for i in 0..n",
            "    var it = Item { id: i, weight: i %% %d, kind: kind_%d(i) }" % (s % 11 + 2, j),
            "    grow_%d(&it, i)" % j,
            "    total += it.id + it.weight + weigh_%d(it.kind)" % j,
            "  total",
        ]
    own = " + ".join("score_%d(n)" % j for j in range(UNITS))
    below = "".join(" + m%04d.score(n)" % c for c in children)
    out += [
        "",
        "// this module's score, and the modules' under it",
        "pub fn score(n: Int) -> Int = (%s%s) %% 1000003" % (own, below),
    ]
    return "\n".join(out) + "\n"


def ren_main(count):
    return "\n".join([
        "// generated by bench/native/gen/gen.py: %d modules" % count,
        "import m0000",
        "",
        "fn main() uses Console = print(m0000.score(3))",
    ]) + "\n"


def go_module(k, count):
    children = [c for c in (2 * k + 1, 2 * k + 2) if c < count]
    out = ["// generated by bench/native/gen/gen.py: module %d of %d" % (k, count)]
    out += ["package m%04d" % k, ""]
    if children:
        out += ["import ("] + ['\t"gen/m%04d"' % c for c in children] + [")", ""]
    out += [
        "type Item struct {",
        "\tID, Weight int",
        "\tKind       Kind",
        "}",
        "",
        "type Kind interface{ isKind() }",
        "",
        "type Small struct{}",
        "type Large struct{ Size int }",
        "type Pair struct{ A, B int }",
        "",
        "func (Small) isKind() {}",
        "func (Large) isKind() {}",
        "func (Pair) isKind()  {}",
    ]
    for j in range(UNITS):
        s = k + j
        out += [
            "",
            "func kind%d(i int) Kind {" % j,
            "\tif i%3 == 0 {",
            "\t\treturn Small{}",
            "\t} else if i%3 == 1 {",
            "\t\treturn Large{i + %d}" % s,
            "\t}",
            "\treturn Pair{i, %d}" % s,
            "}",
            "",
            "func weigh%d(k Kind) int {" % j,
            "\tswitch k := k.(type) {",
            "\tcase Small:",
            "\t\treturn %d" % (s % 10),
            "\tcase Large:",
            "\t\treturn k.Size*2 + %d" % (s % 7),
            "\tcase Pair:",
            "\t\treturn k.A + k.B%%%d" % (s % 5 + 1),
            "\t}",
            "\tpanic(\"unreachable\")",
            "}",
            "",
            "func grow%d(it *Item, by int) {" % j,
            "\tit.Weight += by + %d" % (s % 3),
            "\tit.ID++",
            "}",
            "",
            "func score%d(n int) int {" % j,
            "\ttotal := 0",
            "\tfor i := 0; i < n; i++ {",
            "\t\tit := Item{ID: i, Weight: i %% %d, Kind: kind%d(i)}" % (s % 11 + 2, j),
            "\t\tgrow%d(&it, i)" % j,
            "\t\ttotal += it.ID + it.Weight + weigh%d(it.Kind)" % j,
            "\t}",
            "\treturn total",
            "}",
        ]
    own = " + ".join("score%d(n)" % j for j in range(UNITS))
    below = "".join(" + m%04d.Score(n)" % c for c in children)
    out += [
        "",
        "// this module's score, and the modules' under it",
        "func Score(n int) int {",
        "\treturn (%s%s) %% 1000003" % (own, below),
        "}",
    ]
    return "\n".join(out) + "\n"


def go_main(count):
    return "\n".join([
        "// generated by bench/native/gen/gen.py: %d modules" % count,
        "package main",
        "",
        "import (",
        '\t"fmt"',
        "",
        '\t"gen/m0000"',
        ")",
        "",
        "func main() { fmt.Println(m0000.Score(3)) }",
    ]) + "\n"


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    if len(sys.argv) != 4 or sys.argv[1] not in ("ren", "go"):
        sys.exit("usage: python3 -I gen.py ren|go <lines> <out>")
    lang, lines, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    module = ren_module if lang == "ren" else go_module
    # every module but the last two is the same length, so the count
    # follows from one of them
    per_module = module(0, 3).count("\n")
    count = max(1, -(-lines // per_module))
    total = 0
    for k in range(count):
        text = module(k, count)
        total += text.count("\n")
        if lang == "ren":
            write(os.path.join(out, "m%04d.ren" % k), text)
        else:
            write(os.path.join(out, "m%04d" % k, "m%04d.go" % k), text)
    if lang == "ren":
        main_text = ren_main(count)
        write(os.path.join(out, "main.ren"), main_text)
    else:
        main_text = go_main(count)
        write(os.path.join(out, "main.go"), main_text)
        write(os.path.join(out, "go.mod"), "module gen\n\ngo 1.22\n")
    total += main_text.count("\n")
    print("%d modules, %d lines, in %s" % (count, total, out))


main()

# `python3 -I gen.py`: writes bench.ren, rust/main.rs and go/main.go from
# research/perfect-hash/code/keys, the keyword kernel of the patterns
# stage (compiler.md, "Patterns stage"; bench/native/RESULTS.md,
# "Patterns stage"). Each set's classifier is written twice in Ren: as
# the `==` chain code writes today (`<set>_chain`) and as a `match` with
# a literal arm a key (`<set>_match`), which step 3 lowers to the
# perfect hash. The Rust twin is a plain `match` (rmatch.rs's shape),
# the Go twin a `switch`. All three build the same queries the same way:
# 90% keys, 10% near misses, a key with `_` added or its last byte made
# `#`, from one LCG.
import os

here = os.path.dirname(os.path.abspath(__file__))
keys_dir = os.path.join(here, "..", "..", "..", "research", "perfect-hash", "code", "keys")
SETS = ["renkw", "jsreserved", "methods", "headers", "json24", "one"]


def keys(name):
    with open(os.path.join(keys_dir, name + ".txt")) as f:
        return [l.rstrip("\n") for l in f if l.strip()]


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ren(with_match=True):
    out = ["""// The patterns stage's keyword kernel (compiler.md, "Patterns stage";
// bench/native/RESULTS.md): identifiers classified against a key set,
// Ren's 35 keywords, JS's 45 reserved words, the 9 HTTP methods, 20
// header names, 24 JSON field names and one key (research/perfect-hash/code/keys),
// 65,536 queries a round, 90% keys and 10% near misses. Each set's
// classifier is written as the `==` chain Ren had before string
// patterns, and as a `match` over literal arms, which compiles to a
// perfect hash. Generated by gen.py; rust/ and go/ are its twins.

"""]
    for s in SETS:
        ks = keys(s)
        out.append(f"fn {s}_chain(s: Str) -> Int =\n")
        for i, k in enumerate(ks):
            out.append(f"  {'if' if i == 0 else 'else if'} s == {q(k)} then {i}\n")
        out.append("  else -1\n\n")
        if with_match:
            out.append(f"fn {s}_match(s: Str) -> Int =\n  match s\n")
            for i, k in enumerate(ks):
                out.append(f"    {q(k)} => {i}\n")
            out.append("    _ => -1\n\n")
    out.append("""// the next number of the LCG every twin shares
fn next(x: Int) -> Int = (x * 1103515245 + 12345) % 2147483648

// [n] queries of [keys]: one in ten a near miss
fn queries(keys: Array<Str>, n: Int) -> Array<Str> =
  var qs: Array<Str> = []
  var x = 42
  for _ in 0..n
    x = next(x)
    let k = keys[x % keys.len()]
    x = next(x)
    if x % 10 != 0 then &qs.push(k)
    else if x / 10 % 2 == 0 then &qs.push(k + "_")
    else &qs.push(k[0..k.byte_len() - 1] + "#")
  qs

""")
    out.append("fn keys(set: Str) -> Array<Str> =\n")
    for i, s in enumerate(SETS):
        lst = ", ".join(q(k) for k in keys(s))
        out.append(f"  {'if' if i == 0 else 'else if'} set == {q(s)} then [{lst}]\n")
    out.append("  else []\n\n")
    out.append("fn classify(set: Str, hashed: Bool, s: Str) -> Int =\n")
    for i, s in enumerate(SETS):
        m = f"{s}_match(s)" if with_match else f"{s}_chain(s)"
        out.append(f"  {'if' if i == 0 else 'else if'} set == {q(s)} then (if hashed then {m} else {s}_chain(s))\n")
    out.append("  else -1\n\n")
    # one loop per set and form, so the classifier is called directly
    for s in SETS:
        for form in ["chain", "match"] if with_match else ["chain"]:
            out.append(f"""fn rounds_{s}_{form}(qs: Array<Str>, rounds: Int) -> Int =
  var t = 0
  for _ in 0..rounds
    for q in qs
      t += {s}_{form}(q) + 1
  t

""")
    out.append("""// [rounds] rounds of [n] queries of [set], by the chain or the match:
// the sum of each answer plus one, which the twins print too
pub fn run(set: Str, hashed: Bool, n: Int, rounds: Int) uses Console =
  let qs = queries(keys(set), n)
  var t = 0
""")
    for i, s in enumerate(SETS):
        m = f"rounds_{s}_match(qs, rounds)" if with_match else f"rounds_{s}_chain(qs, rounds)"
        out.append(f"  {'if' if i == 0 else 'else if'} set == {q(s)} then t = if hashed then {m} else rounds_{s}_chain(qs, rounds)\n")
    out.append("""  print(t)

// every set, both forms, which must agree with each other
pub fn check(n: Int) uses Console =
""")
    out.append("  for set in [" + ", ".join(q(s) for s in SETS) + "]\n")
    out.append("""    let qs = queries(keys(set), n)
    var a = 0
    var b = 0
    for q in qs
      a += classify(set, false, q) + 1
      b += classify(set, true, q) + 1
    print(set + " " + show(a) + " " + show(b))
""")
    return "".join(out)


def rust():
    out = ["""// The keyword kernel's Rust twin (bench/native/keywords, gen.py): each
// set a plain `match`, rmatch.rs's shape. `main <set> <n> <rounds>`.
use std::env;

"""]
    for s in SETS:
        out.append(f"#[inline]\nfn {s}(s: &str) -> i64 {{\n    match s {{\n")
        for i, k in enumerate(keys(s)):
            out.append(f"        {q(k)} => {i},\n")
        out.append("        _ => -1,\n    }\n}\n\n")
    out.append("fn keys(set: &str) -> Vec<&'static str> {\n    match set {\n")
    for s in SETS:
        out.append(f"        {q(s)} => vec![{', '.join(q(k) for k in keys(s))}],\n")
    out.append("        _ => vec![],\n    }\n}\n\n")
    out.append("""fn next(x: i64) -> i64 {
    (x * 1103515245 + 12345) % 2147483648
}

fn queries(keys: &[&str], n: usize) -> Vec<String> {
    let mut qs = Vec::with_capacity(n);
    let mut x: i64 = 42;
    for _ in 0..n {
        x = next(x);
        let k = keys[(x % keys.len() as i64) as usize];
        x = next(x);
        if x % 10 != 0 {
            qs.push(k.to_string());
        } else if x / 10 % 2 == 0 {
            qs.push(format!("{}_", k));
        } else {
            qs.push(format!("{}#", &k[..k.len() - 1]));
        }
    }
    qs
}

fn rounds(f: fn(&str) -> i64, qs: &[String], r: usize) -> i64 {
    let mut t = 0;
    for _ in 0..r {
        for q in qs {
            t += f(q) + 1;
        }
    }
    t
}

fn main() {
    let a: Vec<String> = env::args().collect();
    let set = a[1].as_str();
    let n: usize = a[2].parse().unwrap();
    let r: usize = a[3].parse().unwrap();
    let qs = queries(&keys(set), n);
    let t = match set {
""")
    for s in SETS:
        out.append(f"        {q(s)} => rounds({s}, &qs, r),\n")
    out.append("        _ => 0,\n    };\n    println!(\"{}\", t);\n}\n")
    return "".join(out)


def go():
    out = ["""// The keyword kernel's Go twin (bench/native/keywords, gen.py): each
// set a `switch`. `main <set> <n> <rounds>`.
package main

import (
\t"fmt"
\t"os"
\t"strconv"
)

"""]
    for s in SETS:
        out.append(f"func {s}(s string) int64 {{\n\tswitch s {{\n")
        for i, k in enumerate(keys(s)):
            out.append(f"\tcase {q(k)}:\n\t\treturn {i}\n")
        out.append("\t}\n\treturn -1\n}\n\n")
    out.append("func keys(set string) []string {\n\tswitch set {\n")
    for s in SETS:
        out.append(f"\tcase {q(s)}:\n\t\treturn []string{{{', '.join(q(k) for k in keys(s))}}}\n")
    out.append("\t}\n\treturn nil\n}\n\n")
    out.append("""func next(x int64) int64 { return (x*1103515245 + 12345) % 2147483648 }

func queries(keys []string, n int) []string {
\tqs := make([]string, 0, n)
\tvar x int64 = 42
\tfor i := 0; i < n; i++ {
\t\tx = next(x)
\t\tk := keys[x%int64(len(keys))]
\t\tx = next(x)
\t\tif x%10 != 0 {
\t\t\tqs = append(qs, k)
\t\t} else if x/10%2 == 0 {
\t\t\tqs = append(qs, k+"_")
\t\t} else {
\t\t\tqs = append(qs, k[:len(k)-1]+"#")
\t\t}
\t}
\treturn qs
}

func rounds(f func(string) int64, qs []string, r int) int64 {
\tvar t int64
\tfor i := 0; i < r; i++ {
\t\tfor _, q := range qs {
\t\t\tt += f(q) + 1
\t\t}
\t}
\treturn t
}

func main() {
\tset := os.Args[1]
\tn, _ := strconv.Atoi(os.Args[2])
\tr, _ := strconv.Atoi(os.Args[3])
\tqs := queries(keys(set), n)
\tvar t int64
\tswitch set {
""")
    for s in SETS:
        out.append(f"\tcase {q(s)}:\n\t\tt = rounds({s}, qs, r)\n")
    out.append("\t}\n\tfmt.Println(t)\n}\n")
    return "".join(out)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    import sys
    # `--chain-only` writes bench.ren without the `match` forms, for a
    # compiler without string patterns
    text = ren(with_match="--chain-only" not in sys.argv)
    write(os.path.join(here, "bench.ren"), text)
    write(os.path.join(here, "rust", "main.rs"), rust())
    write(os.path.join(here, "go", "main.go"), go())

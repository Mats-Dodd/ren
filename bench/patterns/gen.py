# `python3 -I gen.py`: writes the key-set programs of bench/patterns
# (compiler.md, "Patterns stage", "The tests") and their `.expected`,
# which Python computes, not Ren: each program classifies every key of
# its sets, and near misses, with a string `match` whose arm `i` is key
# `i`, and prints the sum of the answers plus one, and the answer of
# each miss. sizes.ren has keys of 0, 1, 16, 17 and 255 bytes and 128
# and 200 arms; hard.ren has the research's adversarial sets
# (research/perfect-hash/verify/fuzz/mkkeys.py): 200 keys over two
# letters, long shared prefixes, keys past 16 bytes, UTF-8.
import os, random

here = os.path.dirname(os.path.abspath(__file__))


def lit(k):
    out = []
    for ch in k:
        if ch in '"\\':
            out.append("\\" + ch)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def program(sets):
    src = ["// Generated by gen.py, which computes the `.expected` too.\n\n"]
    expected = []
    for name, keys in sets:
        keys = list(dict.fromkeys(keys))
        src.append(f"fn {name}(s: Str) -> Int =\n  match s\n")
        for i, k in enumerate(keys):
            src.append(f"    {lit(k)} => {i}\n")
        src.append("    _ => -1\n\n")
    src.append("fn main() uses Console =\n")
    for name, keys in sets:
        keys = list(dict.fromkeys(keys))
        ks = set(keys)
        src.append(f"  var {name}_t = 0\n")
        for k in keys:
            src.append(f"  {name}_t += {name}({lit(k)}) + 1\n")
        src.append(f"  print({name}_t)\n")
        expected.append(str(sum(i + 1 for i in range(len(keys)))))
        misses = []
        for k in keys[:20]:
            for m in (k + "_", k[:-1] if k else "#", "#" + k):
                if m not in ks and m not in misses:
                    misses.append(m)
        src.append(f"  print([")
        src.append(", ".join(f"{name}({lit(m)})" for m in misses))
        src.append("])\n")
        expected.append("[" + ", ".join("-1" for _ in misses) + "]")
    return "".join(src), "\n".join(expected) + "\nexit 0\n"


def write(name, sets):
    src, exp = program(sets)
    with open(os.path.join(here, name + ".ren"), "w") as f:
        f.write(src)
    with open(os.path.join(here, name + ".expected"), "w") as f:
        f.write(exp)



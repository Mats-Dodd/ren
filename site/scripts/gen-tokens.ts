// Generates src/system/tokens.stylex.ts from src/system/palette.ts.
import { writeFileSync } from 'node:fs';
import { color, font, size, space, rule, measure } from '../src/system/palette.ts';

const q = (s: string) => JSON.stringify(s);
const px = (n: number) => q(`${n / 16}rem`);

// Light is the default and the only automatic mode. Paper is the point; dark is opt-in.
const colorVars = Object.entries(color).map(([k, v]) => `  ${k}: ${q(v.light)},`).join('\n');
const lightTheme = Object.entries(color).map(([k, v]) => `  ${k}: ${q(v.light)},`).join('\n');
const darkTheme = Object.entries(color).map(([k, v]) => `  ${k}: ${q(v.dark)},`).join('\n');

const out = `// GENERATED by scripts/gen-tokens.ts from palette.ts. Do not edit.
import * as stylex from '@stylexjs/stylex';

export const colors = stylex.defineVars({
${colorVars}
});

export const fonts = stylex.defineVars({
${Object.entries(font).map(([k, v]) => `  ${k}: ${q(v.stack)},`).join('\n')}
});

export const sizes = stylex.defineVars({
${Object.entries(size).map(([k, v]) => `  ${k}: ${px(v.px)},`).join('\n')}
});

export const space = stylex.defineVars({
${Object.entries(space).map(([k, v]) => `  ${k}: ${px(v)},`).join('\n')}
});

export const rules = stylex.defineVars({
${Object.entries(rule).map(([k, v]) => `  ${k}: ${q(`${v}px`)},`).join('\n')}
});

export const measure = stylex.defineVars({
${Object.entries(measure).map(([k, v]) => `  ${k}: ${q(v)},`).join('\n')}
});

export const bp = stylex.defineConsts({
  wide: '@media (min-width: 72rem)',
  narrow: '@media (max-width: 47.99rem)',
});

// Applied to <html> by the theme switch.
export const lightTheme = stylex.createTheme(colors, {
${lightTheme}
});

export const darkTheme = stylex.createTheme(colors, {
${darkTheme}
});
`;
writeFileSync(new URL('../src/system/tokens.stylex.ts', import.meta.url), out);
console.log('tokens.stylex.ts written');
